def extract_toc(text):
    toc = []
    lines = text.split('\n')
    idx = 1
    for line in lines:
        line = line.strip()
        if line.startswith('## '):
            heading = line.replace('## ', '').strip().rstrip('#').strip()
            anchor = f'sec-{idx}'
            toc.append({'id': anchor, 'text': heading, 'level': 2})
            idx += 1
        elif line.startswith('### ') and len(toc) < 15:
            heading = line.replace('### ', '').strip().rstrip('#').strip()
            anchor = f'sec-{idx}'
            toc.append({'id': anchor, 'text': heading, 'level': 3})
            idx += 1
    return toc[:12]

def extract_legal_basis(text):
    laws = set()
    # Find citations like ст. 105 УК РФ, ГК РФ, УПК РФ etc.
    patterns = [
        r'(?:ст\.|стать[яеи]\s*)\s*\d+(?:\.\d+)?(?:\s*ч\.\s*\d+)?\s*(?:УК|ГК|УПК|ГПК|КАС|БК|НК)\s*РФ',
        r'Постановлени[ея]\s*Пленума\s*Верховного\s*Суда\s*РФ[^\.\n;]+',
        r'Федеральн\w+\s*закон\w*\s*«[^»]+»',
        r'Конституци\w+\s*Российской\s*Федерации'
    ]
    for p in patterns:
        for m in re.finditer(p, text, re.IGNORECASE):
            raw = m.group(0).strip().rstrip('.,;:')
            raw = re.sub(r'\s+', ' ', raw)
            if len(raw) > 5 and len(raw) < 90:
                laws.add(raw)
    return list(sorted(laws))[:8]

def generate_short_content(title, text):
    # Extract first 4-8 bullet points or definitions
    bullets = []
    lines = text.split('\n')
    for line in lines:
        line = line.strip()
        if line.startswith('* **') or line.startswith('- **') or line.startswith('1. **') or line.startswith('2. **'):
            clean = re.sub(r'[*_#]', '', line).strip()
            if len(clean) > 20 and len(clean) < 300:
                bullets.append(f'- {clean}')
        if len(bullets) >= 6:
            break
    if not bullets:
        # Fallback to key paragraphs
        for line in lines:
            if line and not line.startswith('#') and not line.startswith('|') and not line.startswith('!['):
                clean = re.sub(r'[*_#]', '', line).strip()
                if len(clean) > 40:
                    bullets.append(f'- {clean[:200]}...')
            if len(bullets) >= 5:
                break
    return f'### Краткий конспект для экспресс-записи и повторения\n\n' + '\n'.join(bullets)

